// ------------------------------------------------------------ повороты и отражения

const ROT_ARROW: Record<string, string> = { "^": ">", ">": "v", v: "<", "<": "^" };
const FLIP_ARROW: Record<string, string> = { "<": ">", ">": "<" };

/** Поворот на 90° по часовой. */
export function rotateMap(m: string[]): string[] {
  const H = m.length, W = m[0].length;
  const out: string[] = [];
  for (let y = 0; y < W; y++) {
    let row = "";
    for (let x = 0; x < H; x++) {
      const ch = m[H - 1 - x][y];
      row += ROT_ARROW[ch] || ch;
    }
    out.push(row);
  }
  return out;
}

export function flipMap(m: string[]): string[] {
  return m.map((r) => [...r].reverse().map((ch) => FLIP_ARROW[ch] || ch).join(""));
}

export function transformMap(m: string[], rot: number, flip: boolean): string[] {
  let r = flip ? flipMap(m) : m;
  for (let i = 0; i < rot; i++) r = rotateMap(r);
  return r;
}

/** Проверка формы: строки равной длины, край из стен и проёмов. */
export function validateChunk(c: ChunkDef): string | null {
  const W = c.map[0].length;
  for (const [i, r] of c.map.entries()) if (r.length !== W) return `${c.id}: строка ${i} длиной ${r.length}, нужно ${W}`;
  const H = c.map.length;
  for (let y = 0; y < H; y++) for (let x = 0; x < W; x++) {
    const edge = x === 0 || y === 0 || x === W - 1 || y === H - 1;
    const ch = c.map[y][x];
    if (edge && ch !== "#" && ch !== "@") return `${c.id}: на краю (${x},${y}) символ «${ch}»`;
    if (!edge && ch === "@") return `${c.id}: проём не на краю (${x},${y})`;
  }
  return null;
}
